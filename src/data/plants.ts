/**
 * PLANT CATALOGUE — the demo inventory for Phase 1.
 * ---------------------------------------------------------------------------
 * This file is the ONLY place plant content lives. No component hardcodes a
 * plant name, image or care value. Replacing this array with rows from a real
 * database (Firebase / Supabase / REST) requires no UI changes at all —
 * see src/services/plantService.ts.
 *
 * PRICING: every plant below intentionally has NO price. Real nursery pricing
 * has not been supplied, and the site never invents one. Add `price: 350` (and
 * optionally `priceUnit`) to a plant and the price, the price filter and the
 * price sort options appear automatically across the site.
 *
 * IMAGES: `art` selects a generated botanical illustration used as demo
 * imagery. To use a real photograph, replace the image entry with
 * `{ src: '/photos/monstera.jpg', alt: '...' }`.
 */

interface PlantSeed extends Omit<Plant, 'id' | 'slug' | 'images'> {}

const definePlant = (seed: PlantSeed): Plant => {
  const slug = seed.name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

  /**
   * Imagery for a plant is always a photograph or an honest placeholder.
   * The manifest in data/photos.ts holds every photograph the site ships
   * with; anything uploaded later through admin Image Management is merged
   * over the top at runtime.
   */
  const real = plantPhotos[slug];
  if (real?.length) {
    return { ...seed, id: slug, slug, images: real };
  }

  // No photograph yet. One placeholder, not three: three identical
  // "coming soon" tiles in a gallery would read as a broken gallery.
  // An admin uploading a photo replaces this automatically.
  return {
    ...seed,
    id: slug,
    slug,
    images: [{
      plant: slug,
      label: seed.name,
      alt: `${seed.name}${seed.botanicalName ? ` (${seed.botanicalName})` : ''}`,
      demo: false,
    }],
  };
};

